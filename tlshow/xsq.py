"""Export an FSEQ as an xLights .xsq so it can be opened and hand-edited in
Tesla's xLights show folder (tesla_xlights_show_folder).

Each run of a constant non-zero value on a channel becomes an "On" effect whose
palette brightness reproduces the value (e.g. 90% = fade on 500 ms). Open the
.xsq in xLights, then Render All and save to regenerate the .fseq.
"""

from __future__ import annotations

from pathlib import Path
from xml.sax.saxutils import quoteattr

import numpy as np

from .channels import CHANNELS, XLIGHTS_MODEL_NAMES
from .fseq import Fseq

BASE_PALETTE = ("C_BUTTON_Palette1=#FFFFFF,C_BUTTON_Palette2=#FF0000,C_BUTTON_Palette3=#00FF00,"
                "C_BUTTON_Palette4=#0000FF,C_BUTTON_Palette5=#FFFF00,C_BUTTON_Palette6=#000000,"
                "C_BUTTON_Palette7=#00FFFF,C_BUTTON_Palette8=#FF00FF,C_CHECKBOX_Palette1=1")


def _pct(value: int) -> int:
    # xLights writes floor(pct * 2.55); invert to the percentage that reproduces `value`
    for p in range(101):
        if int(p * 2.55) == value:
            return p
    return round(value / 2.55)


def export(seq: Fseq, out: str | Path, media_file: str = "lightshow.wav", song: str = "",
           artist: str = "") -> Path:
    ms = seq.step_ms
    palettes: list[int] = []
    elements: list[str] = []
    eid = 0
    for name, model in XLIGHTS_MODEL_NAMES.items():
        if name == "DISPLAY_R":
            continue
        col = seq.channel(CHANNELS[name]).astype(int)
        effects = []
        d = np.flatnonzero(np.diff(np.r_[-1, col, -1]))
        for a, b in zip(d[:-1], d[1:]):
            v = col[a]
            if v == 0:
                continue
            pct = _pct(v)
            if pct not in palettes:
                palettes.append(pct)
            effects.append(f'        <Effect ref="0" name="On" id="{eid}" startTime="{a * ms}" '
                           f'endTime="{b * ms}" palette="{palettes.index(pct)}"/>')
            eid += 1
        layer = "\n".join(effects)
        elements.append(f'    <Element type="model" name={quoteattr(model)}>\n      <EffectLayer>\n'
                        f'{layer}\n      </EffectLayer>\n    </Element>')
    pal_xml = "\n".join(f"    <ColorPalette>{BASE_PALETTE},C_SLIDER_Brightness={p}</ColorPalette>"
                        for p in palettes)
    disp = "\n".join(f'    <Element collapsed="0" type="model" name={quoteattr(m)} visible="1"/>'
                     for k, m in XLIGHTS_MODEL_NAMES.items() if k != "DISPLAY_R")
    xml = f"""<?xml version="1.0" encoding="UTF-8"?>
<xsequence BaseChannel="0" ChanCtrlBasic="0" ChanCtrlColor="0" FixedPointTiming="1" ModelBlending="true">
  <head>
    <version>2024.15</version>
    <author>tlshow</author>
    <author-email></author-email>
    <author-website></author-website>
    <song>{song}</song>
    <artist>{artist}</artist>
    <album></album>
    <MusicURL></MusicURL>
    <comment>Generated by tlshow; Render All before saving the fseq.</comment>
    <sequenceTiming>{ms} ms</sequenceTiming>
    <sequenceType>Media</sequenceType>
    <mediaFile>{media_file}</mediaFile>
    <sequenceDuration>{seq.duration_s:.3f}</sequenceDuration>
    <imageDir/>
  </head>
  <nextid>1</nextid>
  <Jukebox/>
  <ColorPalettes>
{pal_xml}
  </ColorPalettes>
  <EffectDB>
    <Effect></Effect>
  </EffectDB>
  <DataLayers>
    <DataLayer lor_params="32727" channel_offset="0" num_channels="0" num_frames="0" data="&lt;rendered: erase-mode&gt;" source="&lt;auto-generated&gt;" name="Nutcracker"/>
  </DataLayers>
  <DisplayElements>
{disp}
  </DisplayElements>
  <ElementEffects>
{chr(10).join(elements)}
  </ElementEffects>
  <lastView>0</lastView>
</xsequence>
"""
    out = Path(out)
    out.write_text(xml)
    return out
